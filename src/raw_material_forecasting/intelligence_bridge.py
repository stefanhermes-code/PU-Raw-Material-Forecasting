"""Register rows as events the forecaster can count.

The application keeps what it reads off HTC Global's own reports in `briefing_register.csv` beside
itself, and the Market Intelligence page reads that file. The forecaster reads something else: the
`event_record` table in the engine's store, by way of `review_job.feature_rows`, which counts events
whose `material` equals the series' chemical.

Until 21 October 2026 nothing carried a row from the first to the second, so every document anyone
imported was visible on a page and invisible to every forecast. This module is the conversion; the
engine's `app/intelligence/inbox.py` is what stores the result.

Kept here rather than in the page so the page and the backfill script cannot drift apart.
"""
from __future__ import annotations

from typing import Any, Iterable

# The engine's own name for this report family. `app/intelligence/inbox.py` refuses anything else.
BRIEFING = "htc_briefing"
CONDITION = "htc_supply_condition"
MONITOR = "htc_price_monitor"


def _text(row: Any, field: str) -> str:
    value = getattr(row, field, "")
    if value is None:
        value = ""
    return str(value).strip()


def chemicals_of(row: Any) -> list[str]:
    """The chemicals a row names, one per event, each under its store code.

    `feature_rows` matches `material` against the series' chemical, so a row stored once under
    "PO;POLYETHER_POLYOL" would be counted for neither. Three chemicals, three events.

    **Upper-casing is not canonicalising**, and that was the gap. A report saying "polyol" became
    `POLYOL`, which migration 0035 retired, and 24 events sat in the store reaching no market -
    polyether polyol's forecast counted 25 events where 49 were about it. `canonical_code` folds a
    retired code forward, so what is written here needs no second rule to read it back.

    The reader folds too, because these 24 rows are already stored and a fix that only works on
    rows written after it is not a fix.
    """
    from .chemicals import canonical_code

    return [canonical_code(part) for part in _text(row, "chemicals").split(";")
            if canonical_code(part)]


def day_of(row: Any) -> str:
    """The day the report spoke for.

    The event's own date where it gave one, otherwise the day the report covered. Never the day it
    was typed in: a forecast cut at a past date must not see an event because somebody imported it
    late, and `available_from` is what every cutoff in this store is applied to.
    """
    return _text(row, "event_date") or _text(row, "reported")


def to_events(rows: Iterable[Any], *, document: str) -> list[dict[str, Any]]:
    """Register rows as the events `app/intelligence/inbox.py` stores. Every row, without exception.

    A row that names a chemical fans out, one event per chemical, because `feature_rows` matches
    `material` exactly. A row that names NONE is still stored, with no material.

    It was left out for one day, on the argument that the forecaster could not count it under any
    series. That argument is wrong twice over. The store is not only read by `feature_rows` - 23 of
    the rows already in `event_record` carry no material either - and more importantly it is not
    this module's business to decide which of HTC Global's own intelligence is worth keeping. These
    reports come from PI3 and the PU Observatory. The Hormuz logistics items, the corporate ones,
    the plant announcements: an event this application cannot yet attach to a price series is
    exactly the kind that explains one later.

    Stefan, 21 October 2026: "These reports are all generated by PI3 and PU Observatory, my 2 PU
    engines who have more industry knowledge than you do. How you think you can gate it??"
    """
    events: list[dict[str, Any]] = []
    for row in rows:
        headline, day = _text(row, "headline"), day_of(row)
        for chemical in (chemicals_of(row) or [""]):
            events.append({
                "evidence_id": f"{document}#{headline[:60]}#{chemical or 'no chemical named'}",
                "event_type": (_text(row, "kind") or "DEVELOPMENT").upper(),
                "material": chemical,
                "headline": headline,
                "available_from": day,
                "document": document,
                "data": {"geographies": _text(row, "geographies"),
                         "confidence": _text(row, "confidence"),
                         "context": _text(row, "context"),
                         "implication": _text(row, "implication"),
                         "quote": _text(row, "quote")},
            })
    return events


def conditions_to_events(conditions: Iterable[Any]) -> list[dict[str, Any]]:
    """A graded chain reading as events, one per chemical an exposure names.

    One reading becomes one event per priced chemical, because `feature_rows` matches `material`
    exactly. An exposure naming no chemical this application prices - "Catalysts, surfactants,
    additives", "Packaging / DG services" - is still sent, with no material: it is the weak
    operational link in most of these reports and losing it would be the same mistake the briefing
    gate made.

    The event carries the grade AND the mechanism. A level on its own says a number changed; the
    mechanism says why, and that is the half a forecast can be explained with.
    """
    events: list[dict[str, Any]] = []
    for condition in conditions:
        day = _text(condition, "reported")
        event_name = _text(condition, "event") or "Supply chain condition"
        state = _text(condition, "state")
        document = _text(condition, "document") or event_name
        exposures = getattr(condition, "exposures", None) or []
        if not exposures and state:
            # The April to June updates grade the chain and never grade the inputs - their authors
            # wrote prose, not a grid. The grade is still the reading, and dropping it would leave
            # the forecaster a four-month hole in a disruption that ran through all of it.
            events.append({
                "evidence_id": f"{document}#{day}#chain",
                "event_type": "SUPPLY_CONDITION",
                "material": "",
                "headline": f"The chain is {state}",
                "available_from": day,
                "document": document,
                "state": state.upper(),
                "data": {"event": event_name, "chain_state": state,
                         "note": _text(condition, "note")},
            })
        for exposure in exposures:
            group = _text(exposure, "group")
            level = _text(exposure, "level")
            mechanism = _text(exposure, "mechanism")
            headline = f"{group}: {level} exposure while the chain is {state}".strip()
            chemicals = [part.strip().upper()
                         for part in _text(exposure, "chemicals").split(";") if part.strip()]
            for chemical in (chemicals or [""]):
                events.append({
                    "evidence_id": f"{document}#{day}#{group}#{chemical or 'no chemical named'}",
                    "event_type": "SUPPLY_CONDITION",
                    "material": chemical,
                    "headline": headline,
                    "available_from": day,
                    "document": document,
                    "state": state.upper() or "ANNOUNCED",
                    "data": {"event": event_name, "chain_state": state, "input_group": group,
                             "exposure_level": level, "mechanism": mechanism,
                             "note": _text(condition, "note")},
                })
    return events


def by_document(rows: Iterable[Any]) -> dict[str, list[Any]]:
    """The rows grouped by the document they were read off, since events are sent per document."""
    out: dict[str, list[Any]] = {}
    for row in rows:
        out.setdefault(_text(row, "document") or "unnamed document", []).append(row)
    return out
